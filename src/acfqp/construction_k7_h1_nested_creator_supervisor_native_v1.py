class ConstructionK7H1NestedCreatorSupervisorNativeV1Error(ValueError):
    """The registered source, static ELF, ABI, or seal contract changed."""


def _fail(message: str) -> NoReturn:
    raise ConstructionK7H1NestedCreatorSupervisorNativeV1Error(message)


def verify_nested_creator_supervisor_native_image_v1() -> dict[str, Any]:
    """Replay source, ELF, static layout, frame ABI, and locked claims."""

    if platform.system() != "Linux" or platform.machine().lower() not in {
        "x86_64",
        "amd64",
    }:
        _fail("nested-creator supervisor is registered only for Linux x86-64")
    try:
        source = SOURCE_PATH.read_bytes()
    except OSError as error:
        raise ConstructionK7H1NestedCreatorSupervisorNativeV1Error(
            "nested-creator supervisor source is unavailable"
        ) from error
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        _fail("nested-creator supervisor source digest changed")
    if (
        len(ROLE_ELF_BYTES) != ELF_BYTE_COUNT
        or hashlib.sha256(ROLE_ELF_BYTES).hexdigest() != ELF_SHA256
    ):
        _fail("nested-creator supervisor ELF image changed")
    if ROLE_ELF_BYTES[:16] != b"\x7fELF\x02\x01\x01" + bytes(9):
        _fail("nested-creator supervisor ELF identity changed")
    (
        elf_type,
        machine,
        elf_version,
        entry,
        program_offset,
        section_offset,
        flags,
        header_bytes,
        program_entry_bytes,
        program_count,
        section_entry_bytes,
        section_count,
        section_string_index,
    ) = struct.unpack_from("<HHIQQQIHHHHHH", ROLE_ELF_BYTES, 16)
    if (
        elf_type != 2
        or machine != 62
        or elf_version != 1
        or entry != 0x401EC2
        or program_offset != 64
        or section_offset != 8016
        or flags != 0
        or header_bytes != 64
        or program_entry_bytes != 56
        or program_count != 3
        or section_entry_bytes != 64
        or section_count != 4
        or section_string_index != 3
    ):
        _fail("nested-creator supervisor ELF header changed")
    program_rows = [
        struct.unpack_from("<IIQQQQQQ", ROLE_ELF_BYTES, program_offset + 56 * index)
        for index in range(program_count)
    ]
    if program_rows != [
        (1, 4, 0, 0x400000, 0x400000, 0xE8, 0xE8, 0x1000),
        (1, 5, 0x1000, 0x401000, 0x401000, 0xF02, 0xF02, 0x1000),
        (0x6474E551, 6, 0, 0, 0, 0, 0, 0x10),
    ]:
        _fail("nested-creator supervisor load or stack segments changed")
    if len(set(OPCODES.values())) != len(OPCODES) or sorted(OPCODES.values()) != list(
        range(1, 13)
    ):
        _fail("nested-creator supervisor opcode registry changed")
    if FRAME_BYTES != 64 or CONTROL_FD != 3 or CHILD_GATE_FD != 4:
        _fail("nested-creator supervisor fixed ABI changed")
    return {
        "source_sha256": SOURCE_SHA256,
        "elf_sha256": ELF_SHA256,
        "elf_byte_count": ELF_BYTE_COUNT,
        "entry_point": entry,
        "program_headers": [list(row) for row in program_rows],
        "frame_magic": FRAME_MAGIC,
        "frame_version": FRAME_VERSION,
        "frame_bytes": FRAME_BYTES,
        "opcodes": dict(OPCODES),
        "pid_cell_bytes": PID_CELL_BYTES,
        "single_nested_pidfd_probe_only": True,
        "creator_wnowait_and_consuming_reap": True,
        "third_wait_requires_echild": True,
        "runtime_toolchain_invocation_present": False,
        "actual_process_birth_present": False,
        "five_birth_process_authority_present": False,
        "official_execution_allowed": False,
    }


def create_sealed_nested_creator_supervisor_memfd_v1() -> int:
    """Return one exact immutable executable memfd; launch nothing."""

    verify_nested_creator_supervisor_native_image_v1()
    if not callable(getattr(os, "memfd_create", None)):
        _fail("memfd_create is unavailable")
    descriptor = os.memfd_create(
        "acfqp-h1-nested-creator-supervisor-v1",
        MFD_CLOEXEC | MFD_ALLOW_SEALING,
    )
    try:
        offset = 0
        while offset < len(ROLE_ELF_BYTES):
            written = os.write(descriptor, ROLE_ELF_BYTES[offset:])
            if written <= 0:
                _fail("nested-creator supervisor memfd write made no progress")
            offset += written
        if os.lseek(descriptor, 0, os.SEEK_SET) != 0:
            _fail("nested-creator supervisor memfd seek changed")
        fcntl.fcntl(descriptor, F_ADD_SEALS, REQUIRED_SEALS)
        status = os.fstat(descriptor)
        if (
            status.st_size != ELF_BYTE_COUNT
            or fcntl.fcntl(descriptor, F_GET_SEALS) != REQUIRED_SEALS
            or os.pread(descriptor, ELF_BYTE_COUNT + 1, 0) != ROLE_ELF_BYTES
            or fcntl.fcntl(descriptor, fcntl.F_GETFD) & fcntl.FD_CLOEXEC == 0
        ):
            _fail("nested-creator supervisor sealed memfd changed")
        return descriptor
    except BaseException:
        os.close(descriptor)
        raise


