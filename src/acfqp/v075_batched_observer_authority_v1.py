def _replay_batch_from_binding(
    *,
    claimed: V075SignedBatchedObservationV1,
    binding: observer.V075ObserverOpenAuthorityBindingV1,
    private_salt: bytes,
    private_environment: tuple[
        tuple[tuple[int, Fraction], ...], ...
    ],
) -> V075BatchedObservationPrivateReplayVerificationV1:
    if (
        type(claimed) is not V075SignedBatchedObservationV1
        or type(binding) is not observer.V075ObserverOpenAuthorityBindingV1
        or claimed.request.observer_open_binding != binding
        or claimed.request.authority_scope is not _scope_from_binding(binding)
    ):
        _fail("private replay batch/authority binding was transplanted")
    try:
        reveal = public.verify_opaque_environment_reveal_v1(
            commitment=binding.namespace.environment_commitment,
            secret_salt=private_salt,
            secret_laws=private_environment,
        )
    except public.V075PublicCampaignAuthorityInvariantViolation as error:
        raise V075BatchedObserverInvariantViolation(str(error)) from error
    if not reveal.matched:
        _fail("private replay environment does not match opaque commitment")
    context = claimed.request.stream_identity.row_binding.context
    contexts = binding.namespace.family.replicate_contexts
    if context != contexts[context.replicate_ordinal]:
        _fail("private replay context/order binding changed")
    try:
        kernel = H2GraphKernelV1(
            context.topology,
            context.rank_cap,
            context.horizon,
            private_environment[context.replicate_ordinal],
        )
        stream_identity = claimed.request.stream_identity
        stream = DeterministicH2GraphStreamV1(
            kernel=kernel,
            state=stream_identity.row_binding.catalogue.state.to_kernel_state(),
            action=H2GraphActionV1(*stream_identity.action),
            remaining_horizon=stream_identity.row_binding.remaining_horizon,
            seed=stream_identity.seed,
        )
        accumulator = _StreamingBatchAccumulatorV1(claimed.request)
        for accepted_index in range(1, claimed.request.accepted_draw_end + 1):
            sample = stream.draw()
            if accepted_index >= claimed.request.accepted_draw_start:
                accumulator.append(sample)
        replayed = accumulator.finish()
    except (
        H2GraphTransitionInvariantViolation,
        IndexError,
    ) as error:
        raise V075BatchedObserverInvariantViolation(str(error)) from error
    if replayed != claimed.facts:
        _fail("signed batch aggregates differ from exact private replay")
    verify_v075_signed_batched_observation_v1(claimed)
    return V075BatchedObservationPrivateReplayVerificationV1(
        _PRIVATE_REPLAY_ISSUER,
        claimed.batch_id,
        claimed.request.request_id,
        binding.binding_id,
        claimed.request.authority_scope,
        claimed.request.accepted_draw_count,
    )


def verify_v075_production_batched_observation_private_replay_v1(
    *,
    claimed: V075SignedBatchedObservationV1,
    authority: "V075ProductionOpenAuthorityV1",
    namespace: public.V075PublicTargetTapeNamespaceV1,
    private_salt: bytes,
    private_environment: private_env.V075PrivateGeneratedEnvironmentV1,
) -> V075BatchedObservationPrivateReplayVerificationV1:
    """Production replay accepts only generated private environment authority."""

    if (
        type(private_environment)
        is not private_env.V075PrivateGeneratedEnvironmentV1
        or type(namespace) is not public.V075PublicTargetTapeNamespaceV1
        or private_environment.family != namespace.family
    ):
        _fail("production batch replay rejects construction/duck environments")
    try:
        binding = observer._require_production_open_binding(
            authority=authority,
            namespace=namespace,
        )
    except observer.V075PrivateObserverBoundaryInvariantViolation as error:
        raise V075BatchedObserverInvariantViolation(str(error)) from error
    return _replay_batch_from_binding(
        claimed=claimed,
        binding=binding,
        private_salt=private_salt,
        private_environment=(
            private_environment.secret_laws_for_commitment()
        ),
    )


