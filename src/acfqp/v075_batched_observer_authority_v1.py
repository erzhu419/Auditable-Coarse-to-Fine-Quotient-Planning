class V075BatchedObserverInvariantViolation(ValueError):
    """A request, batch, signature, sequence, or replay invariant failed."""


def _fail(message: str) -> None:
    raise V075BatchedObserverInvariantViolation(message)


def _hash(role: str, payload: Mapping[str, Any]) -> str:
    try:
        return hashlib.sha256(
            DOMAIN_TAGS[role].encode("utf-8")
            + b"\x00"
            + canonical_json_bytes(dict(payload))
        ).hexdigest()
    except (KeyError, TypeError, ValueError) as error:
        raise V075BatchedObserverInvariantViolation(str(error)) from error


def _cid(value: Any, field_name: str) -> str:
    try:
        return parse_content_id(value)
    except ValueError as error:
        raise V075BatchedObserverInvariantViolation(
            f"{field_name} must be one lowercase SHA-256 content ID"
        ) from error


def _fdoc(value: Fraction) -> dict[str, int]:
    if type(value) is not Fraction:
        _fail("batched observer arithmetic must use exact Fraction")
    return {
        "numerator": value.numerator,
        "denominator": value.denominator,
    }


def _fraction_from_document(value: Any, field_name: str) -> Fraction:
    if type(value) is Fraction:
        return value
    if (
        type(value) is not dict
        or frozenset(value) != {"numerator", "denominator"}
        or type(value["numerator"]) is not int
        or type(value["denominator"]) is not int
        or value["denominator"] <= 0
    ):
        _fail(f"{field_name} is not one exact rational")
    result = Fraction(value["numerator"], value["denominator"])
    if _fdoc(result) != value:
        _fail(f"{field_name} is not reduced canonical rational form")
    return result


def _exact_mapping(
    value: Any,
    keys: set[str],
    *,
    field_name: str,
) -> dict[str, Any]:
    if (
        type(value) is not dict
        or frozenset(value) != frozenset(keys)
        or any(type(key) is not str for key in value)
    ):
        _fail(f"{field_name} field set is missing or contains unknown fields")
    return value


def _strict_load(raw: bytes, *, field_name: str) -> dict[str, Any]:
    if type(raw) is not bytes or len(raw) > MAX_CANONICAL_BATCH_BYTES:
        _fail(f"{field_name} must be capped canonical bytes")
    try:
        value = loads_canonical_json(raw)
    except Phase3EIdentityError as error:
        raise V075BatchedObserverInvariantViolation(str(error)) from error
    if type(value) is not dict or canonical_json_bytes(value) != raw:
        _fail(f"{field_name} is not one canonical object")
    return value


class V075BatchAuthorityScopeV1(str, Enum):
    PRODUCTION_OPEN = "PRODUCTION_OPEN"
    CONSTRUCTION_ONLY = "CONSTRUCTION_ONLY"


def _scope_from_binding(
    binding: observer.V075ObserverOpenAuthorityBindingV1,
) -> V075BatchAuthorityScopeV1:
    if (
        type(binding) is not observer.V075ObserverOpenAuthorityBindingV1
    ):
        _fail("batch session has a foreign observer-open binding")
    if (
        binding.scope
        is observer.V075ObserverOpenAuthorityScopeV1.PRODUCTION_OPEN
    ):
        return V075BatchAuthorityScopeV1.PRODUCTION_OPEN
    if (
        binding.scope
        is observer.V075ObserverOpenAuthorityScopeV1.CONSTRUCTION_ONLY
    ):
        return V075BatchAuthorityScopeV1.CONSTRUCTION_ONLY
    _fail("batch session has an unknown authority scope")
    raise AssertionError("unreachable")


_REQUEST_ISSUER = object()


@dataclass(frozen=True, slots=True)
class V075BatchedObservationRequestV1:
    _issuer: object
    session_public_id: str
    observer_open_binding: observer.V075ObserverOpenAuthorityBindingV1
    stream_identity: graph.V075TransitionStreamIdentityV1
    authority_scope: V075BatchAuthorityScopeV1
    accepted_draw_start: int
    accepted_draw_count: int
    accepted_draw_cap: int
    _request_id: str = field(init=False, repr=False)

    def __post_init__(self) -> None:
        _cid(self.session_public_id, "batch request observer session")
        end = self.accepted_draw_start + self.accepted_draw_count - 1
        if (
            self._issuer is not _REQUEST_ISSUER
            or type(self.observer_open_binding)
            is not observer.V075ObserverOpenAuthorityBindingV1
            or type(self.stream_identity)
            is not graph.V075TransitionStreamIdentityV1
            or self.stream_identity.namespace
            != self.observer_open_binding.namespace
            or type(self.authority_scope) is not V075BatchAuthorityScopeV1
            or self.authority_scope
            is not _scope_from_binding(self.observer_open_binding)
            or type(self.accepted_draw_start) is not int
            or self.accepted_draw_start <= 0
            or type(self.accepted_draw_count) is not int
            or not 0 < self.accepted_draw_count
            <= MAX_BATCH_ACCEPTED_DRAW_COUNT
            or type(self.accepted_draw_cap) is not int
            or not 0 < self.accepted_draw_cap <= MAX_ACCEPTED_DRAW_CAP
            or end > self.accepted_draw_cap
        ):
            _fail("batch request is untyped, over-cap, or authority-transplanted")
        object.__setattr__(
            self,
            "_request_id",
            _hash("request", self._payload()),
        )

    @property
    def accepted_draw_end(self) -> int:
        return self.accepted_draw_start + self.accepted_draw_count - 1

    @property
    def request_id(self) -> str:
        return self._request_id

    def _payload(self) -> dict[str, Any]:
        stream = self.stream_identity
        return {
            "schema": "acfqp.v075_batched_observation_request.v1",
            "schema_version": SCHEMA_VERSION,
            "profile_key": PROFILE_KEY,
            "observer_session_public_id": self.session_public_id,
            "observer_open_binding_id": self.observer_open_binding.binding_id,
            "authority_scope": self.authority_scope.value,
            "target_tape_namespace_id": stream.target_tape_namespace_id,
            "environment_commitment_id": (
                self.observer_open_binding.namespace.environment_commitment
                .commitment_id
            ),
            "context_id": stream.context_id,
            "context_ordinal": (
                stream.row_binding.context.replicate_ordinal
            ),
            "row_binding_id": stream.row_binding_id,
            "catalogue_id": stream.catalogue_id,
            "stream_id": stream.stream_id,
            "pairing_group_id": stream.pairing_group_id,
            "support_epoch_id": stream.support_epoch_id,
            "observer_epoch_index": stream.observer_epoch_index,
            "lane": stream.lane.value,
            "arm": stream.arm,
            "accepted_draw_start": self.accepted_draw_start,
            "accepted_draw_count": self.accepted_draw_count,
            "accepted_draw_end": self.accepted_draw_end,
            "accepted_draw_cap": self.accepted_draw_cap,
            "request_nonce_allowed": False,
            "reroll_allowed": False,
            "private_material_serialized": False,
        }

    def to_document(self) -> dict[str, Any]:
        return {
            **self._payload(),
            "observer_open_binding": self.observer_open_binding.to_document(),
            "stream_identity": self.stream_identity.to_document(),
            "request_id": self.request_id,
        }

    @property
    def canonical_bytes(self) -> bytes:
        return canonical_json_bytes(self.to_document())


def _issue_request(
    *,
    session: observer.V075PrivateObserverSessionV1,
    stream_identity: graph.V075TransitionStreamIdentityV1,
    accepted_draw_start: int,
    accepted_draw_count: int,
    accepted_draw_cap: int,
) -> V075BatchedObservationRequestV1:
    if (
        type(session) is not observer.V075PrivateObserverSessionV1
        or type(stream_identity)
        is not graph.V075TransitionStreamIdentityV1
        or stream_identity.namespace != session.authority_binding.namespace
    ):
        _fail("batch request issuer requires an exact session and stream")
    return V075BatchedObservationRequestV1(
        _REQUEST_ISSUER,
        session.session_public_id,
        session.authority_binding,
        stream_identity,
        _scope_from_binding(session.authority_binding),
        accepted_draw_start,
        accepted_draw_count,
        accepted_draw_cap,
    )


@dataclass(frozen=True, slots=True)
class V075BatchedPublicOutcomeAggregateV1:
    next_ranks: tuple[int, ...]
    failure: bool
    terminal: bool
    spawn_cell: int
    spawn_rank: int
    realized_row_reward: Fraction
    count: int
    reward_sum: Fraction

    def __post_init__(self) -> None:
        if (
            type(self.next_ranks) is not tuple
            or not self.next_ranks
            or any(type(rank) is not int or rank < 0 for rank in self.next_ranks)
            or type(self.failure) is not bool
            or type(self.terminal) is not bool
            or type(self.spawn_cell) is not int
            or self.spawn_cell < 0
            or type(self.spawn_rank) is not int
            or self.spawn_rank <= 0
            or type(self.realized_row_reward) is not Fraction
            or self.realized_row_reward < 0
            or type(self.count) is not int
            or self.count <= 0
            or type(self.reward_sum) is not Fraction
            or self.reward_sum != self.realized_row_reward * self.count
        ):
            _fail("public outcome aggregate is malformed")

    def _outcome_payload(self) -> dict[str, Any]:
        return {
            "schema": "acfqp.v075_batched_public_outcome.v1",
            "schema_version": SCHEMA_VERSION,
            "next_ranks": list(self.next_ranks),
            "failure": self.failure,
            "terminal": self.terminal,
            "spawn_cell": self.spawn_cell,
            "spawn_rank": self.spawn_rank,
            "realized_row_reward": _fdoc(self.realized_row_reward),
        }

    @property
    def outcome_id(self) -> str:
        return _hash("outcome", self._outcome_payload())

    def to_document(self) -> dict[str, Any]:
        return {
            **self._outcome_payload(),
            "outcome_id": self.outcome_id,
            "count": self.count,
            "reward_sum": _fdoc(self.reward_sum),
        }


def _sample_leaf_payload(sample: H2GraphSampleV1) -> dict[str, Any]:
    if type(sample) is not H2GraphSampleV1:
        _fail("transcript leaf requires one exact sample")
    return {
        "schema": "acfqp.v075_batched_observation_transcript_leaf.v1",
        "schema_version": SCHEMA_VERSION,
        "accepted_draw_index": sample.accepted_draw_index,
        "random_word_start_index": sample.random_word_start_index,
        "random_words": list(sample.random_words),
        "next_ranks": list(sample.next_state.ranks),
        "failure": sample.failure,
        "terminal": sample.terminal,
        "spawn_cell": sample.spawn_cell,
        "spawn_rank": sample.spawn_rank,
        "realized_row_reward": _fdoc(sample.realized_row_reward),
    }


class _StreamingBatchAccumulatorV1:
    __slots__ = (
        "_accepted_count",
        "_failure_count",
        "_first_random_word_index",
        "_outcomes",
        "_random_word_count",
        "_rejection_count",
        "_request",
        "_reward_sum",
        "_terminal_count",
        "_transcript_state",
    )

    def __init__(self, request: V075BatchedObservationRequestV1) -> None:
        if type(request) is not V075BatchedObservationRequestV1:
            _fail("batch accumulator requires one exact request")
        self._request = request
        self._accepted_count = 0
        self._failure_count = 0
        self._terminal_count = 0
        self._random_word_count = 0
        self._rejection_count = 0
        self._reward_sum = Fraction(0)
        self._first_random_word_index: int | None = None
        self._outcomes: dict[
            tuple[Any, ...],
            tuple[int, Fraction],
        ] = {}
        self._transcript_state = hashlib.sha256(
            TRANSCRIPT_INITIAL_DOMAIN
            + b"\x00"
            + request.request_id.encode("ascii")
        ).digest()

    def append(self, sample: H2GraphSampleV1) -> None:
        expected_index = (
            self._request.accepted_draw_start + self._accepted_count
        )
        if (
            type(sample) is not H2GraphSampleV1
            or sample.accepted_draw_index != expected_index
            or (
                self._first_random_word_index is not None
                and sample.random_word_start_index
                != self._first_random_word_index + self._random_word_count
            )
        ):
            _fail("batch sample interval is gapped, overlapped, or reordered")
        if self._first_random_word_index is None:
            self._first_random_word_index = sample.random_word_start_index
        key = (
            sample.next_state.ranks,
            sample.failure,
            sample.terminal,
            sample.spawn_cell,
            sample.spawn_rank,
            sample.realized_row_reward,
        )
        prior_count, prior_reward = self._outcomes.get(
            key,
            (0, Fraction(0)),
        )
        self._outcomes[key] = (
            prior_count + 1,
            prior_reward + sample.realized_row_reward,
        )
        self._accepted_count += 1
        self._failure_count += int(sample.failure)
        self._terminal_count += int(sample.terminal)
        self._random_word_count += sample.random_word_count
        self._rejection_count += sample.rejection_count
        self._reward_sum += sample.realized_row_reward
        leaf = hashlib.sha256(
            TRANSCRIPT_LEAF_DOMAIN
            + b"\x00"
            + canonical_json_bytes(_sample_leaf_payload(sample))
        ).digest()
        self._transcript_state = hashlib.sha256(
            TRANSCRIPT_STEP_DOMAIN
            + b"\x00"
            + self._transcript_state
            + b"\x00"
            + leaf
        ).digest()

    def finish(self) -> "_BatchFactsV1":
        if (
            self._accepted_count != self._request.accepted_draw_count
            or self._first_random_word_index is None
        ):
            _fail("batch accumulator did not cover the complete request")
        outcomes = tuple(
            sorted(
                (
                    V075BatchedPublicOutcomeAggregateV1(
                        key[0],
                        key[1],
                        key[2],
                        key[3],
                        key[4],
                        key[5],
                        count,
                        reward,
                    )
                    for key, (count, reward) in self._outcomes.items()
                ),
                key=lambda item: item.outcome_id,
            )
        )
        return _BatchFactsV1(
            outcomes,
            self._reward_sum,
            self._failure_count,
            self._terminal_count,
            self._random_word_count,
            self._rejection_count,
            self._first_random_word_index,
            self._first_random_word_index + self._random_word_count,
            self._transcript_state.hex(),
        )


@dataclass(frozen=True, slots=True)
class _BatchFactsV1:
    outcomes: tuple[V075BatchedPublicOutcomeAggregateV1, ...]
    reward_sum: Fraction
    failure_count: int
    terminal_count: int
    random_word_count: int
    rejection_count: int
    first_random_word_index: int
    next_random_word_index: int
    transcript_commitment: str

    def __post_init__(self) -> None:
        _cid(self.transcript_commitment, "batch transcript commitment")
        accepted = sum(item.count for item in self.outcomes)
        if (
            type(self.outcomes) is not tuple
            or not self.outcomes
            or any(
                type(item) is not V075BatchedPublicOutcomeAggregateV1
                for item in self.outcomes
            )
            or tuple(item.outcome_id for item in self.outcomes)
            != tuple(sorted(item.outcome_id for item in self.outcomes))
            or len({item.outcome_id for item in self.outcomes})
            != len(self.outcomes)
            or type(self.reward_sum) is not Fraction
            or self.reward_sum
            != sum(
                (item.reward_sum for item in self.outcomes),
                Fraction(0),
            )
            or type(self.failure_count) is not int
            or self.failure_count
            != sum(item.count for item in self.outcomes if item.failure)
            or type(self.terminal_count) is not int
            or self.terminal_count
            != sum(item.count for item in self.outcomes if item.terminal)
            or type(self.random_word_count) is not int
            or self.random_word_count < accepted
            or type(self.rejection_count) is not int
            or self.rejection_count != self.random_word_count - accepted
            or type(self.first_random_word_index) is not int
            or self.first_random_word_index <= 0
            or self.next_random_word_index
            != self.first_random_word_index + self.random_word_count
        ):
            _fail("batch aggregate facts do not reconcile")


