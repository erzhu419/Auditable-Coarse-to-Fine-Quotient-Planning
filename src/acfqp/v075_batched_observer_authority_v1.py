def verify_v075_batched_observation_sequence_v1(
    batches: tuple[V075SignedBatchedObservationV1, ...],
) -> V075BatchedObservationSequenceVerificationV1:
    if (
        type(batches) is not tuple
        or not batches
        or any(type(item) is not V075SignedBatchedObservationV1 for item in batches)
    ):
        _fail("batch sequence requires a nonempty exact typed tuple")
    first = batches[0].request
    expected_start = 1
    for batch in batches:
        verify_v075_signed_batched_observation_v1(batch)
        request = batch.request
        if (
            request.session_public_id != first.session_public_id
            or request.observer_open_binding != first.observer_open_binding
            or request.stream_identity != first.stream_identity
            or request.authority_scope is not first.authority_scope
            or request.accepted_draw_cap != first.accepted_draw_cap
            or request.accepted_draw_start != expected_start
        ):
            _fail(
                "batch sequence is gapped, overlapping, reordered, "
                "or context/arm transplanted"
            )
        expected_start = request.accepted_draw_end + 1
    return V075BatchedObservationSequenceVerificationV1(
        _SEQUENCE_VERIFIER_ISSUER,
        first.session_public_id,
        first.stream_identity.stream_id,
        tuple(item.batch_id for item in batches),
        expected_start - 1,
        first.accepted_draw_cap,
    )


