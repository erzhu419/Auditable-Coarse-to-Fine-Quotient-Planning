"""Signed, exact, streaming observation batches for V0-075.

This authority replaces one public record and RSA signature per draw with one
signed aggregate over a contiguous accepted-draw interval.  Samples are still
generated by the same :class:`DeterministicH2GraphStreamV1`; aggregation is
streaming and therefore changes neither the tape nor exact arithmetic.

Public artifacts contain outcome counts, exact reward sums, failure/terminal
counts, random-word/rejection accounting, and a deterministic hash-chain
commitment to every underlying sample.  They contain no law, salt, kernel,
random seed, or individual random word.

Production and construction authority paths are exact-type separated.
Independent private replay regenerates the interval from the beginning and
compares the complete aggregate without serializing private material.
"""

