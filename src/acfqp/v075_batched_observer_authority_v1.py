class V075PrivateBatchedObserverSessionV1:
    """Exclusive streaming adapter over one exact private observer session."""

    __slots__ = (
        "_accepted_cap_by_stream",
        "_aggregate_support_evidence_by_id",
        "_batches",
        "_executed_request_ids",
        "_failed",
        "_issued_validation_row_ids",
        "_session",
    )

    def __init__(
        self,
        *,
        session: observer.V075PrivateObserverSessionV1,
        issuer: object,
    ) -> None:
        if (
            issuer is not _BATCH_SESSION_ISSUER
            or type(session) is not observer.V075PrivateObserverSessionV1
            or session.journal_entries
            or getattr(session, "_closed", True)
        ):
            _fail(
                "batched adapter requires one open, unused exact observer session"
            )
        self._session = session
        self._accepted_cap_by_stream: dict[str, int] = {}
        self._aggregate_support_evidence_by_id: dict[
            str,
            graph.V075BatchAggregateSupportEvidenceV1,
        ] = {}
        self._executed_request_ids: set[str] = set()
        self._issued_validation_row_ids: set[str] = set()
        self._batches: list[V075SignedBatchedObservationV1] = []
        self._failed = False

    @property
    def session_public_id(self) -> str:
        return self._session.session_public_id

    @property
    def authority_scope(self) -> V075BatchAuthorityScopeV1:
        return _scope_from_binding(self._session.authority_binding)

    @property
    def batches(self) -> tuple[V075SignedBatchedObservationV1, ...]:
        return tuple(self._batches)

    def freeze_aggregate_support_evidence_v1(
        self,
        *,
        discovery_batch: V075SignedBatchedObservationV1,
        selected_outcome_ids: tuple[str, ...],
    ) -> tuple[graph.V075BatchAggregateSupportEvidenceV1, ...]:
        """Freeze signed support from aggregate DISCOVERY outcomes.

        No individual draw is reconstructed or assigned an index.  A
        subsequent VALIDATION request is accepted only when its support epoch
        contains evidence frozen through this exact session before that
        request was issued.
        """

        if (
            type(discovery_batch) is not V075SignedBatchedObservationV1
            or discovery_batch not in self._batches
            or discovery_batch.request.session_public_id
            != self._session.session_public_id
            or discovery_batch.request.observer_open_binding
            != self._session.authority_binding
            or discovery_batch.request.stream_identity.lane
            is not graph.V075ObservationLaneV1.DISCOVERY
            or discovery_batch.request.stream_identity.observer_epoch_index
            != 0
            or type(selected_outcome_ids) is not tuple
            or not selected_outcome_ids
            or selected_outcome_ids
            != tuple(sorted(set(selected_outcome_ids)))
            or len(selected_outcome_ids)
            > graph.MAX_SUPPORT_MEMBERS_PER_ROW
        ):
            _fail(
                "aggregate support freeze requires one completed DISCOVERY "
                "batch and canonical observed outcomes"
            )
        row = discovery_batch.request.stream_identity.row_binding
        if row.row_binding_id in self._issued_validation_row_ids:
            _fail("aggregate support cannot change after validation issuance")
        outcome_by_id = {
            item.outcome_id: item for item in discovery_batch.outcomes
        }
        if not set(selected_outcome_ids) <= set(outcome_by_id):
            _fail("aggregate support selected an unobserved DISCOVERY outcome")
        signer = getattr(self._session, "_signer", None)
        expected_key = (
            self._session.authority_binding.namespace.signer_registry
            .observer_evidence_key
        )
        evidence: list[graph.V075BatchAggregateSupportEvidenceV1] = []
        observed_state_ids: set[str] = set()
        for outcome_id in selected_outcome_ids:
            outcome = outcome_by_id[outcome_id]
            observed_state = graph.V075SymbolicGraphStateV1(
                row.context,
                outcome.next_ranks,
                outcome.failure,
            )
            if observed_state.state_id in observed_state_ids:
                _fail(
                    "aggregate support cannot multiply one projected state "
                    "through spawn-identity aliases"
                )
            observed_state_ids.add(observed_state.state_id)
            message = (
                graph.batch_aggregate_support_evidence_signing_bytes_v1(
                    namespace=self._session.authority_binding.namespace,
                    row_binding=row,
                    observed_state=observed_state,
                    source_observer_epoch_index=0,
                    discovery_request_id=discovery_batch.request.request_id,
                    discovery_batch_id=discovery_batch.batch_id,
                    discovery_outcome_id=outcome.outcome_id,
                    discovery_outcome_count=outcome.count,
                )
            )
            try:
                signature = observer._sign(
                    signer=signer,
                    expected_key=expected_key,
                    message=message,
                )
                item = graph.bind_batch_aggregate_support_evidence_v1(
                    namespace=self._session.authority_binding.namespace,
                    row_binding=row,
                    observed_state=observed_state,
                    source_observer_epoch_index=0,
                    discovery_request_id=discovery_batch.request.request_id,
                    discovery_batch_id=discovery_batch.batch_id,
                    discovery_outcome_id=outcome.outcome_id,
                    discovery_outcome_count=outcome.count,
                    observer_signature_hex=signature,
                )
            except (
                observer.V075PrivateObserverBoundaryInvariantViolation,
                graph.V075PublicGraphSemanticsInvariantViolation,
            ) as error:
                raise V075BatchedObserverInvariantViolation(
                    str(error)
                ) from error
            evidence.append(item)
        result = tuple(sorted(evidence, key=lambda item: item.evidence_id))
        for item in result:
            self._aggregate_support_evidence_by_id[item.evidence_id] = item
        return result

    def issue_request_v1(
        self,
        *,
        stream_identity: graph.V075TransitionStreamIdentityV1,
        accepted_draw_start: int,
        accepted_draw_count: int,
        accepted_draw_cap: int,
    ) -> V075BatchedObservationRequestV1:
        if (
            self._failed
            or self._session.journal_entries
            or getattr(self._session, "_closed", True)
            or type(stream_identity)
            is not graph.V075TransitionStreamIdentityV1
        ):
            _fail("per-draw and batched observer paths cannot be mixed")
        is_validation = (
            stream_identity.lane
            is graph.V075ObservationLaneV1.VALIDATION
        )
        if is_validation:
            evidence = stream_identity.pairing_authority.support_chain.leaf.evidence
            if (
                not evidence
                or any(
                    type(item)
                    is not graph.V075BatchAggregateSupportEvidenceV1
                    or self._aggregate_support_evidence_by_id.get(
                        item.evidence_id
                    )
                    != item
                    or item.row_binding != stream_identity.row_binding
                    or item.source_observer_epoch_index != 0
                    for item in evidence
                )
            ):
                _fail(
                    "validation request lacks pre-frozen batch aggregate "
                    "DISCOVERY support"
                )
        request = _issue_request(
            session=self._session,
            stream_identity=stream_identity,
            accepted_draw_start=accepted_draw_start,
            accepted_draw_count=accepted_draw_count,
            accepted_draw_cap=accepted_draw_cap,
        )
        prior_cap = self._accepted_cap_by_stream.get(stream_identity.stream_id)
        if prior_cap is not None and prior_cap != accepted_draw_cap:
            _fail("one stream cannot reroll by changing its accepted-draw cap")
        stream = getattr(self._session, "_streams", {}).get(
            stream_identity.stream_id
        )
        current = 0 if stream is None else stream.accepted_draw_count
        if accepted_draw_start != current + 1:
            _fail("batch request start is gapped, overlapping, or stale")
        if is_validation:
            self._issued_validation_row_ids.add(
                stream_identity.row_binding_id
            )
        return request

    def execute_request_v1(
        self,
        request: V075BatchedObservationRequestV1,
    ) -> V075SignedBatchedObservationV1:
        if (
            type(request) is not V075BatchedObservationRequestV1
            or request.session_public_id != self._session.session_public_id
            or request.observer_open_binding != self._session.authority_binding
            or request.authority_scope is not self.authority_scope
            or request.request_id in self._executed_request_ids
            or self._failed
            or self._session.journal_entries
            or getattr(self._session, "_closed", True)
        ):
            _fail("batch request is reused, transplanted, or mixed with records")
        stream_identity = request.stream_identity
        prior_cap = self._accepted_cap_by_stream.get(stream_identity.stream_id)
        if prior_cap is not None and prior_cap != request.accepted_draw_cap:
            _fail("batch execution cap changed after its first request")
        kernels = getattr(self._session, "_kernels", None)
        streams = getattr(self._session, "_streams", None)
        if type(kernels) is not dict or type(streams) is not dict:
            _fail("private observer implementation changed under batch adapter")
        kernel = kernels.get(stream_identity.context_id)
        if type(kernel) is not H2GraphKernelV1:
            _fail("batch adapter lacks the bound private context kernel")
        stream = streams.get(stream_identity.stream_id)
        if stream is None:
            try:
                stream = DeterministicH2GraphStreamV1(
                    kernel=kernel,
                    state=(
                        stream_identity.row_binding.catalogue.state
                        .to_kernel_state()
                    ),
                    action=H2GraphActionV1(*stream_identity.action),
                    remaining_horizon=(
                        stream_identity.row_binding.remaining_horizon
                    ),
                    seed=stream_identity.seed,
                )
            except H2GraphTransitionInvariantViolation as error:
                raise V075BatchedObserverInvariantViolation(str(error)) from error
            streams[stream_identity.stream_id] = stream
        if stream.accepted_draw_count + 1 != request.accepted_draw_start:
            _fail("batch execution interval is gapped, overlapping, or stale")
        # Once the deterministic tape advances, any exception must close this
        # adapter rather than allowing an unaccounted retry.
        self._failed = True
        accumulator = _StreamingBatchAccumulatorV1(request)
        for _index in range(request.accepted_draw_count):
            accumulator.append(stream.draw())
        facts = accumulator.finish()
        signer = getattr(self._session, "_signer", None)
        expected_key = (
            request.observer_open_binding.namespace.signer_registry
            .observer_evidence_key
        )
        try:
            signature = observer._sign(
                signer=signer,
                expected_key=expected_key,
                message=batched_observation_signing_bytes_v1(
                    request=request,
                    facts=facts,
                ),
            )
        except observer.V075PrivateObserverBoundaryInvariantViolation as error:
            raise V075BatchedObserverInvariantViolation(str(error)) from error
        result = V075SignedBatchedObservationV1(
            request,
            facts.outcomes,
            facts.reward_sum,
            facts.failure_count,
            facts.terminal_count,
            facts.random_word_count,
            facts.rejection_count,
            facts.first_random_word_index,
            facts.next_random_word_index,
            facts.transcript_commitment,
            signature,
        )
        self._accepted_cap_by_stream[stream_identity.stream_id] = (
            request.accepted_draw_cap
        )
        self._executed_request_ids.add(request.request_id)
        self._batches.append(result)
        self._failed = False
        return result


